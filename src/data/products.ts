export function getProductsByCategory(categorySlug: string): Product[] {
  const normalizedSlug = categorySlug ? categorySlug.toLowerCase().trim() : "";
  // Map aliases
  const aliasMap: Record<string, string> = {
    playground: "playground-recreation",
    "playground-recreation": "playground-recreation",
    "kids-zone": "kids-educational",
    "kids-educational": "kids-educational",
    montessori: "kids-educational",
    "school-furniture": "kindergarten-furniture",
    "kindergarten-furniture": "kindergarten-furniture",
    kindergarten: "kindergarten-furniture",
    sports: "sports-equipment",
    "sports-equipment": "sports-equipment",
    turf: "artificial-turf",
    "artificial-turf": "artificial-turf",
    fitness: "commercial-fitness",
    "commercial-fitness": "commercial-fitness",
    gym: "commercial-fitness",
  };
  const resolved = aliasMap[normalizedSlug] || normalizedSlug;

  return ALL_PRODUCTS.filter(
    (p) =>
      p.categorySlug === resolved ||
      p.categorySlug.toLowerCase().includes(resolved) ||
      p.category.toLowerCase().includes(resolved.replace("-", " "))
  );
}

export function getProductsBySubcategory(
  categorySlug: string,
  subcategorySlug: string
): Product[] {
  const categoryProducts = getProductsByCategory(categorySlug);
  if (!subcategorySlug || subcategorySlug === "all") {
    return categoryProducts;
  }
  const normSub = subcategorySlug.toLowerCase().trim();
  return categoryProducts.filter(
    (p) =>
      p.subcategorySlug === normSub ||
      p.subcategorySlug.toLowerCase().includes(normSub) ||
      p.subcategory.toLowerCase().includes(normSub.replace("-", " "))
  );
}

